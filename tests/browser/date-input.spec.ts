import { test, expect } from '@playwright/test';

test('fechas: escritura, borrado junto a barra, edición de mes, pegado y validación', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-30T12:00:00+01:00') });
  await page.goto('/');
  await page.getByRole('radio', { name: 'Hijo', exact: true }).click();
  await page.getByRole('radio', { name: 'Días fijos y fines de semana alternos', exact: true }).click();
  await page.getByRole('button', { name: 'Continuar', exact: true }).click();
  const start = page.getByRole('textbox', { name: 'Inicio de la rutina' });
  await start.fill('');
  await start.pressSequentially('30102026');
  await expect(start).toHaveValue('30/10/2026');
  await start.pressSequentially('99');
  await expect(start).toHaveValue('30/10/2026');
  await start.evaluate((input: HTMLInputElement) => { input.focus(); input.setSelectionRange(3, 3); });
  await start.press('Backspace');
  await expect(start).toHaveValue('31/02/026');
  expect(await start.evaluate((input: HTMLInputElement) => input.selectionStart)).toBe(1);
  await start.fill('30.10.2026');
  await expect(start).toHaveValue('30/10/2026');
  await start.evaluate((input: HTMLInputElement) => { input.focus(); input.setSelectionRange(3, 5); });
  await start.pressSequentially('11');
  await expect(start).toHaveValue('30/11/2026');
  expect(await start.evaluate((input: HTMLInputElement) => input.selectionStart)).toBe(5);
  await start.press('ControlOrMeta+A');
  await start.press('Backspace');
  await expect(start).toHaveValue('');
  await start.fill('31022026');
  await page.getByRole('button', { name: 'Revisar respuestas', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('La fecha no existe');
  await start.fill('30102026');
  const friday = page.getByRole('textbox', { name: 'Viernes de referencia' });
  await friday.fill('30-10-2026');
  await expect(friday).toHaveValue('30/10/2026');
  await page.getByRole('radio', { name: 'Fin de semana de referencia: Madre', exact: true }).click();
  await page.getByRole('button', { name: 'Revisar respuestas', exact: true }).click();
  await page.getByRole('button', { name: 'Guardar rutina y ver calendario', exact: true }).click();
  await page.getByRole('button', { name: 'Añadir cambio puntual', exact: true }).click();
  await page.getByRole('textbox', { name: 'Fecha inicial' }).fill('31102026');
  await page.getByRole('textbox', { name: 'Fecha final' }).fill('31/10/2026');
  await expect(page.getByRole('textbox', { name: 'Fecha inicial' })).toHaveValue('31/10/2026');
  await expect(page.getByRole('textbox', { name: 'Fecha final' })).toHaveValue('31/10/2026');
  await page.getByRole('radio', { name: 'Con padre' }).click();
  await page.getByRole('button', { name: 'Guardar cambio puntual', exact: true }).click();
  await expect(page.getByRole('button', { name: '31 de octubre de 2026, con padre', exact: true })).toBeVisible();
});
